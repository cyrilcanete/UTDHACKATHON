// Start `python app.py` in demo mode, then run with Playwright available to Node.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch({headless:true,args:['--no-sandbox']});
  const page = await browser.newPage({viewport:{width:1440,height:1080}});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const artifacts=process.env.MIRROR_TEST_ARTIFACTS;
  if(artifacts) fs.mkdirSync(artifacts,{recursive:true});
  try {
    await page.goto('http://127.0.0.1:5000');
    await page.getByRole('button',{name:"Scan Cyril's card"}).waitFor();
    assert.equal(await page.locator('#greeting').innerText(),'Hello, Cyril.');
    await page.getByRole('button',{name:'Example delivery scam',exact:true}).click();
    await page.getByRole('button',{name:'Review message',exact:true}).click();
    await page.locator('#review-result:not([hidden])').waitFor();
    assert.equal(await page.locator('#review-verdict').innerText(),'Review before acting');
    assert.equal(await page.locator('#review-signals li').count(),3);
    await page.getByRole('button',{name:'Example ordinary reminder',exact:true}).click();
    await page.getByRole('button',{name:'Review message',exact:true}).click();
    await page.locator('#review-result:not([hidden])').waitFor();
    assert.equal(await page.locator('#review-verdict').innerText(),'No common warning signs detected');
    await page.locator('#message-text').fill('m p f');
    assert.equal(await page.locator('body').getAttribute('data-view'),'personal');
    if(artifacts) await page.screenshot({path:path.join(artifacts,'personal.png'),fullPage:true});
    await page.getByRole('button',{name:'Work',exact:true}).click();
    await page.locator('body[data-view="work"]').waitFor();
    assert.equal(await page.locator('#summary').innerText(),'');
    assert.equal(await page.locator('#metric-temperature').innerText(),'23.5°C');
    await page.getByRole('button',{name:'Cooling issue',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('#metric-temperature').textContent==='35.0°C');
    assert.equal(await page.locator('#work-alerts li').count(),2);
    if(artifacts) await page.screenshot({path:path.join(artifacts,'work.png'),fullPage:true});
    await page.getByRole('button',{name:"Scan Sarah's card",exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('#greeting').textContent==='Hello, Sarah.');
    assert.equal(await page.locator('body').getAttribute('data-view'),'personal');
    assert.match(await page.locator('#events').innerText(),/Sarah/);
    assert.equal(await page.locator('#message-text').inputValue(),'');
    assert.equal(await page.locator('#review-result').isVisible(),false);
    await page.getByRole('button',{name:"Scan Cyril's card",exact:true}).click();
    await page.locator('body[data-view="work"]').waitFor();
    await page.getByRole('button',{name:'Sensor offline',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('#metric-temperature').textContent==='—');
    assert.match(await page.locator('#work-heading').innerText(),/unavailable/i);
    await page.getByRole('button',{name:'Normal',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('#metric-temperature').textContent==='23.5°C');
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    if(artifacts) await page.screenshot({path:path.join(artifacts,'mobile.png'),fullPage:true});
    await page.getByRole('button',{name:'Personal',exact:true}).click();
    await page.locator('body[data-view="personal"]').waitFor();
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.getByRole('button',{name:'Hide personal details',exact:true}).click();
    assert.equal(await page.locator('#personal-panels').isVisible(),false);
    await page.getByRole('button',{name:'Show personal details',exact:true}).click();
    assert.equal(await page.locator('#personal-panels').isVisible(),true);
    assert.deepEqual(errors,[]);
    console.log('PASS: profile switching, mode memory, message review, alerts, offline/recovery, privacy, keyboard typing and mobile layouts.');
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exit(1);});
